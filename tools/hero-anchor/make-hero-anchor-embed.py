#!/usr/bin/env python3
"""Build webflow/hero-anchor-embed.html: the CSS behind the R2 Hero
"Image anchor" and "Image anchor (phone)" props.

The props bind to data-anchor and data-anchor-phone on hero-r2_image.
Value format: "X Y" in percent (0-100, % optional), or words
(top, bottom, left, right, center, in any order, hyphen or space).
Prefix selectors read X, suffix selectors read Y. Empty or unknown = center.

Two copies in Webflow, both class hero-r2_anchor-css (display none), each
right after the hero image; paste the same file into both:
  1. R2 Hero component (Hero, group R2)
  2. Destinations Template, whose hero is an unlinked copy; there data-anchor
     is bound straight to the CMS field "Hero image anchor".

Run: python3 tools/hero-anchor/make-hero-anchor-embed.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "webflow" / "hero-anchor-embed.html"


def rules(attr, vx, vy):
    out = []
    # Words. "center" sets nothing, so it falls back to 50%.
    out.append(f'[{attr}^="left" i],[{attr}$="left" i]{{{vx}:0%}}')
    out.append(f'[{attr}^="right" i],[{attr}$="right" i]{{{vx}:100%}}')
    out.append(f'[{attr}^="top" i],[{attr}$="top" i]{{{vy}:0%}}')
    out.append(f'[{attr}^="bottom" i],[{attr}$="bottom" i]{{{vy}:100%}}')
    # Numbers: X is the first value (followed by a space), Y the last.
    for n in range(101):
        out.append(f'[{attr}^="{n} "],[{attr}^="{n}% "]{{{vx}:{n}%}}')
    for n in range(101):
        out.append(f'[{attr}$=" {n}"],[{attr}$=" {n}%"]{{{vy}:{n}%}}')
    return out


def main():
    lines = [
        "<!-- R2 Hero image anchor. Generated by nsbh-webflow/tools/hero-anchor/",
        "     make-hero-anchor-embed.py; edit the script, not this file.",
        "     Lives in a Code Embed inside the R2 Hero component (hero-r2_anchor-css).",
        "     Image anchor -> data-anchor; Image anchor (phone) -> data-anchor-phone",
        "     (767px and below; empty = use Image anchor).",
        '     Type "X Y" in % (0-100): "50 0" top, "30 20", "70% 40%". Words: top,',
        "     bottom-left, left top, right. Empty or unknown = center. -->",
        "<style>",
        ".hero-r2_image[data-anchor]{object-position:var(--ax,50%) var(--ay,50%)}",
        '@media screen and (max-width:767px){.hero-r2_image[data-anchor-phone]:not([data-anchor-phone=""]){object-position:var(--pax,50%) var(--pay,50%)}}',
    ]
    lines += rules("data-anchor", "--ax", "--ay")
    lines += rules("data-anchor-phone", "--pax", "--pay")
    lines.append("</style>")
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
